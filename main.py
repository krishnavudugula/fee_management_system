@app.post("/api/admin/propose-fee")
def propose_new_fee(payload: ProposeFeeRequest, db: Session = Depends(get_db)):
    """Admin proposes a new fee and applies it to all matching students"""
    try:
        # 1. Create the fee category
        fee_category = models.FeeCategory(
            title=payload.title,
            description=payload.description,
            default_amount=payload.amount,
            target_audience=payload.target_audience
        )
        db.add(fee_category)
        db.flush()  # Get the ID

        # 2. Apply to all matching students
        if payload.target_audience.upper() == "ALL":
            students = db.query(models.User).filter(models.User.role == models.RoleType.STUDENT).all()
        else:
            students = db.query(models.User).filter(
                models.User.role == models.RoleType.STUDENT,
                models.User.branch == payload.target_audience
            ).all()

        # 3. Create student dues for each student with is_proposed flag
        for student in students:
            due = models.StudentDue(
                student_id=student.id,
                fee_category_id=fee_category.id,
                total_amount=payload.amount,
                paid_amount=0.0,
                status=models.StatusType.PENDING,
                is_proposed=1
            )
            db.add(due)

        db.commit()
        return {
            "message": f"Fee proposed successfully and applied to {len(students)} students",
            "students_count": len(students)
        }
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=f"Failed to propose fee: {str(e)}")


