@app.get("/api/student/dashboard/{student_id}")
def get_student_dashboard(student_id: int, db: Session = Depends(get_db)):
    # 1. Get the student profile
    student = db.query(models.User).filter(models.User.id == student_id).first()
    if not student:
        raise HTTPException(status_code=404, detail="Student not found")
    
    # 2. Get their specific fee allocations
    dues = db.query(models.StudentDue).filter(models.StudentDue.student_id == student_id).all()

    pending_transactions = db.query(models.Transaction).filter(
        models.Transaction.student_id == student_id,
        models.Transaction.status == models.TransactionStatus.PENDING_APPROVAL
    ).all()

    pending_by_category = {}
    for transaction in pending_transactions:
        key = transaction.fee_category_id
        pending_by_category[key] = pending_by_category.get(key, 0) + transaction.amount_paid
    
    # 3. Package the data for the frontend
    fees_data = []
    for due in dues:
        pending_amount = pending_by_category.get(due.fee_category_id, 0)
        fees_data.append({
            "category": due.fee_category.title,
            "description": due.fee_category.description,
            "total": due.total_amount,
            "paid": due.paid_amount,
            "pending": pending_amount,
            "is_proposed": bool(due.is_proposed)
        })

    recent_transactions = db.query(models.Transaction).filter(
        models.Transaction.student_id == student_id
    ).order_by(models.Transaction.submitted_at.desc()).limit(5).all()

    activity_data = []
    for transaction in recent_transactions:
        status_label = "Pending Approval"
        if transaction.status == models.TransactionStatus.VERIFIED:
            status_label = "Verified"
        elif transaction.status == models.TransactionStatus.REJECTED:
            status_label = "Rejected"

        activity_data.append({
            "category": get_fee_category_title(db, transaction.fee_category_id),
            "amount": transaction.amount_paid,
            "status": status_label,
            "utr": transaction.utr_number,
            "date": transaction.submitted_at.strftime("%d %b %Y") if transaction.submitted_at else ""
        })
        
    return {
        "student_name": student.full_name,
        "roll_number": student.roll_number,
        "branch": student.branch,
        "fees": fees_data,
        "recent_activity": activity_data
    }


@app.post("/api/student/submit-payment")
async def submit_payment_proof(
    student_id: int = Form(...),
    category: str = Form(...),
    amount: float = Form(...),
    utr_number: str = Form(...),
    proof_file: UploadFile = File(...),
    db: Session = Depends(get_db)
):
    student = db.query(models.User).filter(models.User.id == student_id).first()
    if not student:
        raise HTTPException(status_code=404, detail="Student not found")

    fee_category = db.query(models.FeeCategory).filter(models.FeeCategory.title == category).first()
    if not fee_category:
        raise HTTPException(status_code=404, detail="Fee category not found")

    due = db.query(models.StudentDue).filter(
        models.StudentDue.student_id == student_id,
        models.StudentDue.fee_category_id == fee_category.id
    ).first()

    if not due:
        raise HTTPException(status_code=404, detail="No due found for selected category")

    pending_sum = db.query(func.sum(models.Transaction.amount_paid)).filter(
        models.Transaction.student_id == student_id,
        models.Transaction.fee_category_id == fee_category.id,
        models.Transaction.status == models.TransactionStatus.PENDING_APPROVAL
    ).scalar() or 0

    remaining = due.total_amount - due.paid_amount - pending_sum
    if amount <= 0:
        raise HTTPException(status_code=400, detail="Amount should be greater than 0")
    if amount > remaining:
        raise HTTPException(status_code=400, detail=f"Amount exceeds remaining due ₹{remaining:.0f}")

    existing_utr = db.query(models.Transaction).filter(models.Transaction.utr_number == utr_number).first()
    if existing_utr:
        raise HTTPException(status_code=400, detail="UTR already submitted")

    file_ext = Path(proof_file.filename or "receipt.jpg").suffix or ".jpg"
    safe_name = f"{uuid.uuid4().hex}{file_ext}"
    saved_path = UPLOADS_DIR / safe_name

    content = await proof_file.read()
    with open(saved_path, "wb") as destination:
        destination.write(content)

    transaction = models.Transaction(
        student_id=student_id,
        fee_category_id=fee_category.id,
        amount_paid=amount,
        utr_number=utr_number,
        receipt_proof_url=f"/uploads/{safe_name}",
        status=models.TransactionStatus.PENDING_APPROVAL
    )
    db.add(transaction)
    db.commit()

    return {"message": "Payment proof submitted for admin verification"}


