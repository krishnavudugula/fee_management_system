@app.post("/api/admin/register-student")
def register_student(student_data: StudentRegistration, db: Session = Depends(get_db)):
    
    # 1. Check if student already exists
    existing_user = db.query(models.User).filter(models.User.roll_number == student_data.roll_number).first()
    if existing_user:
        raise HTTPException(status_code=400, detail="Student with this Roll Number already exists.")

    # 2. Create the User Profile
    new_student = models.User(
        full_name=student_data.full_name,
        email=f"{student_data.roll_number.lower()}@bitsnarsampet.ac.in",
        password_hash=student_data.password, # Note: In production, use bcrypt to hash this!
        role=models.RoleType.STUDENT,
        roll_number=student_data.roll_number,
        branch=student_data.branch
    )
    db.add(new_student)
    db.commit()
    db.refresh(new_student) # Gets the new ID generated by the database

    # 3. Create the Fee Allocations for this student
    for fee in student_data.fees:
        # Check if the fee category exists in the DB, if not, create it dynamically
        category = db.query(models.FeeCategory).filter(models.FeeCategory.title == fee.category).first()
        if not category:
            category = models.FeeCategory(title=fee.category, default_amount=fee.amount, target_audience="ALL")
            db.add(category)
            db.commit()
            db.refresh(category)

        # Link the fee to the student in the StudentDue table
        new_due = models.StudentDue(
            student_id=new_student.id,
            fee_category_id=category.id,
            total_amount=fee.amount,
            paid_amount=0.0,
            status=models.StatusType.PENDING
        )
        db.add(new_due)
    
    db.commit()

    return {"message": "Student successfully registered and fees allocated.", "student_id": new_student.id}
@app.get("/api/admin/dashboard-stats")
def get_dashboard_stats(db: Session = Depends(get_db)):
    # 1. Count active students
    total_students = db.query(models.User).filter(models.User.role == models.RoleType.STUDENT).count()

    # 2. Calculate Total Paid and Total Due across the entire institute
    totals = db.query(
        func.sum(models.StudentDue.total_amount).label('total_allocated'),
        func.sum(models.StudentDue.paid_amount).label('total_paid')
    ).first()

    total_allocated = totals.total_allocated or 0
    total_paid = totals.total_paid or 0
    total_due = total_allocated - total_paid

    # 3. Fetch students who owe money for the Defaulters Table
    # This SQL query joins the User and StudentDue tables, groups them by student, and filters for due > 0
    defaulters_query = db.query(
        models.User.full_name,
        models.User.roll_number,
        models.User.branch,
        func.sum(models.StudentDue.total_amount - models.StudentDue.paid_amount).label('pending_amount')
    ).join(models.StudentDue).group_by(models.User.id).having(
        func.sum(models.StudentDue.total_amount - models.StudentDue.paid_amount) > 0
    ).all()

    # Format the data for the frontend
    defaulters_list = [
        {
            "id": row.roll_number,
            "name": row.full_name,
            "branch": row.branch,
            "due": row.pending_amount
        } for row in defaulters_query
    ]

    return {
        "active_enrollments": total_students,
        "total_paid": total_paid,
        "total_due": total_due,
        "total_allocated": total_allocated,
        "defaulters": defaulters_list
    }
