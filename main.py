def push_alert_for_student(student_id: int, title: str, message: str, notification_type: str = "ALERT"):
    notifications = ALERT_STORE.get(student_id, [])
    notifications.insert(0, {
        "id": f"NTF-{int(datetime.utcnow().timestamp() * 1000)}-{student_id}",
        "type": notification_type,
        "title": title,
        "message": message,
        "time": "Just now",
        "read": False
    })
    ALERT_STORE[student_id] = notifications[:20]


