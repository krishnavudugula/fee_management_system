@app.post("/api/admin/verification-action/{transaction_id}")
def process_verification_action(transaction_id: int, payload: VerificationActionRequest, db: Session = Depends(get_db)):
    transaction = db.query(models.Transaction).filter(models.Transaction.id == transaction_id).first()
    if not transaction:
        raise HTTPException(status_code=404, detail="Transaction not found")

    if transaction.status != models.TransactionStatus.PENDING_APPROVAL:
        raise HTTPException(status_code=400, detail="Transaction already processed")

    action = payload.action.strip().lower()
    if action not in ["approve", "reject"]:
        raise HTTPException(status_code=400, detail="Invalid action")

    try:
        if action == "approve":
            due = db.query(models.StudentDue).filter(
                models.StudentDue.student_id == transaction.student_id,
                models.StudentDue.fee_category_id == transaction.fee_category_id
            ).first()

            if not due:
                raise HTTPException(status_code=404, detail="Student due not found")

            due.paid_amount = min(due.total_amount, due.paid_amount + transaction.amount_paid)
            due.status = models.StatusType.CLEARED if due.paid_amount >= due.total_amount else models.StatusType.PENDING
            transaction.status = models.TransactionStatus.VERIFIED

            category_title = get_fee_category_title(db, transaction.fee_category_id)
            receipt_no = build_receipt_no(transaction.id)

            # 1) Approval notification
            push_alert_for_student(
                transaction.student_id,
                "Payment Approved",
                f"Approved: ₹{transaction.amount_paid:,.0f} for {category_title} (UTR: {transaction.utr_number}).",
                notification_type="PAYMENT"
            )

            # 2) Receipt issued notification
            push_alert_for_student(
                transaction.student_id,
                "Receipt Issued",
                f"Receipt {receipt_no} is available in Document Center for ₹{transaction.amount_paid:,.0f} ({category_title}).",
                notification_type="PAYMENT"
            )
        else:
            reason = (payload.reason or "Payment proof did not meet verification requirements.").strip()
            if not reason:
                raise HTTPException(status_code=400, detail="Rejection reason is required")

            transaction.status = models.TransactionStatus.REJECTED
            REJECTION_REASON_STORE[transaction.id] = reason

            push_alert_for_student(
                transaction.student_id,
                "Payment Rejected",
                f"Your payment proof was rejected: {reason}. Amount will be refunded to your original payment account.",
                notification_type="PAYMENT"
            )

        db.commit()
        message = "Transaction approved successfully" if action == "approve" else "Transaction rejected successfully"
        return {"message": message}
    except SQLAlchemyError:
        db.rollback()
        raise HTTPException(status_code=500, detail="Failed to process verification")


